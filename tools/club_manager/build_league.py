"""Builds lib/data/manager_league_clubs.dart: the real clubs of the solo Club Manager league.

The solo league used to be twenty made-up names (Northgate FC, Canark XI). Its
opponents are now popular clubs (lib/data/popular_clubs_pool.dart), each measured
the way the player's own squad is built: from known players of every era (gameplay
rating 72+, functions/config/pvp_catalog.json.gz) who played for the club
(player_clubs in the V4 database). A club's rating is the average of its best known
XI (1 goalkeeper, 4 defenders, 3 midfielders, 3 forwards); a club without such an XI
is left out. Its best known forwards and midfielders score its goals in the match
report. Current squads are not used: the database's open spells are incomplete.

    py -3 tools/club_manager/build_league.py           # write
    py -3 tools/club_manager/build_league.py --check   # fail on drift
"""
import argparse, gzip, json, re, shutil, sqlite3, subprocess, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'lib/data/manager_league_clubs.dart'
NEED = {'GK': 1, 'DF': 4, 'MF': 3, 'FW': 3}
KNOWN = 72


def build():
    src = (ROOT / 'lib/data/popular_clubs_pool.dart').read_text(encoding='utf-8')
    body = src.split('popularClubIds = [')[1].split('];')[0]
    ids = list(dict.fromkeys(int(x) for x in re.findall(r'^\s*(\d+),', body, re.M)))
    pv = json.loads(gzip.decompress((ROOT / 'functions/config/pvp_catalog.json.gz').read_bytes()))
    rating = {int(k): v['rating'] for k, v in pv['players'].items()}
    db = sqlite3.connect(ROOT / 'assets/runtime/linkball_game_data_v4.sqlite')
    clubs = []
    for cid in ids:
        row = db.execute('select name, competition, badge_key, color from clubs where id=?', (cid,)).fetchone()
        if not row: continue
        people = db.execute('''select pc.player_id, p.name, pr.position_group from player_clubs pc
            join players p on p.id = pc.player_id left join profiles pr on pr.player_id = pc.player_id
            where pc.club_id = ?''', (cid,)).fetchall()
        known = sorted(((rating[pid], name, group, pid) for pid, name, group in people
                        if rating.get(pid, 0) >= KNOWN), key=lambda x: (-x[0], x[3]))
        xi = [x for g, n in NEED.items() for x in [k for k in known if k[2] == g][:n]]
        if len(xi) < 11: continue
        clubs.append(dict(id=cid, name=row[0], league=row[1] or '', badgeKey=row[2], color=row[3],
            rating=round(sum(x[0] for x in xi) / 11, 1),
            forwards=[x[1] for x in known if x[2] == 'FW'][:4],
            midfielders=[x[1] for x in known if x[2] == 'MF'][:3]))
    clubs.sort(key=lambda c: (-c['rating'], c['id']))
    assert len(clubs) >= 30, len(clubs)
    return clubs


def dart(clubs):
    s = lambda v: "'" + v.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"
    out = ['// GENERATED by tools/club_manager/build_league.py. Do not edit by hand.',
           '// Real clubs of the solo Club Manager league, rated by their best known XI.', '',
           "import '../models/manager_league_club.dart';", '',
           'const managerLeagueClubs = <ManagerLeagueClub>[']
    for c in clubs:
        out += ['  ManagerLeagueClub(',
                f"    id: {c['id']},",
                f"    name: {s(c['name'])},",
                f"    league: {s(c['league'])},",
                *([f"    badgeKey: {s(c['badgeKey'])},"] if c['badgeKey'] else []),
                *([f"    color: {c['color']},"] if c['color'] is not None else []),
                f"    rating: {c['rating']},",
                f"    forwards: [{', '.join(s(n) for n in c['forwards'])}],",
                f"    midfielders: [{', '.join(s(n) for n in c['midfielders'])}],",
                '  ),']
    out += ['];', '']
    return '\n'.join(out)


def formatted(text):
    # The file is kept as `dart format` writes it.
    tool = shutil.which('dart') or 'C:/Development/flutter/bin/dart.bat'
    with tempfile.TemporaryDirectory() as d:
        f = Path(d) / 'manager_league_clubs.dart'; f.write_text(text, encoding='utf-8', newline='\n')
        subprocess.run([tool, 'format', str(f)], check=True, capture_output=True, shell=tool.endswith('.bat'))
        return f.read_text(encoding='utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = formatted(dart(build()))
    if args.check:
        assert OUT.read_text(encoding='utf-8') == text, 'manager_league_clubs.dart drift: rebuild it'
    else:
        OUT.write_text(text, encoding='utf-8', newline='\n')
    print(text.count('ManagerLeagueClub('), 'clubs')
